<template>
  <div class="flex flex-col gap-6">
    <!-- General Subtitles Options -->
    <base-fieldset
      :legend="t('subtitles.title')"
      :label="t('subtitles.options.enable.legendLabel')"
    >
      <div class="flex flex-col gap-5 my-2">
        <!-- Enable Subtitles Toggle -->
        <div class="flex items-center justify-between p-3 rounded-lg border border-base-content/10 bg-base-200/50">
          <div>
            <label class="font-semibold text-sm cursor-pointer" for="enable-subtitles">
              {{ t('subtitles.options.enable.label') }}
            </label>
            <p class="text-xs text-base-content/70 mt-0.5">
              {{ t('subtitles.options.enable.hint') }}
            </p>
          </div>
          <input
            id="enable-subtitles"
            v-model="settings.subtitles.enabled"
            type="checkbox"
            class="toggle toggle-primary"
          />
        </div>

        <!-- Subtitle Preferences Grid -->
        <div class="grid gap-4 md:grid-cols-2" :class="{ 'opacity-50 pointer-events-none': !settings.subtitles.enabled }">
          <!-- Auto-generated Subtitles -->
          <div class="flex flex-col justify-between p-3 rounded-lg border border-base-content/10 bg-base-200/30">
            <div>
              <label class="font-semibold text-sm cursor-pointer" for="auto-generated-subtitles">
                {{ t('subtitles.options.autoGenerated.label') }}
              </label>
              <p class="text-xs text-base-content/70 mt-0.5">
                {{ t('subtitles.options.autoGenerated.hint') }}
              </p>
            </div>
            <div class="mt-3">
              <input
                id="auto-generated-subtitles"
                v-model="settings.subtitles.includeAutoGenerated"
                type="checkbox"
                class="toggle toggle-primary"
              />
            </div>
          </div>

          <!-- Embed Subtitles in Video -->
          <div class="flex flex-col justify-between p-3 rounded-lg border border-base-content/10 bg-base-200/30">
            <div>
              <label class="font-semibold text-sm cursor-pointer" for="embed-subtitles">
                {{ t('subtitles.options.embed.label') }}
              </label>
              <p class="text-xs text-base-content/70 mt-0.5">
                {{ t('subtitles.options.embed.hint') }}
              </p>
            </div>
            <div class="mt-3">
              <input
                id="embed-subtitles"
                v-model="settings.subtitles.embedSubtitles"
                type="checkbox"
                class="toggle toggle-primary"
              />
            </div>
          </div>
        </div>

        <!-- Subtitle Format -->
        <div class="flex flex-col gap-1.5" :class="{ 'opacity-50 pointer-events-none': !settings.subtitles.enabled }">
          <label class="font-semibold text-sm" for="format-select">
            {{ t('subtitles.options.format.label') }}
          </label>
          <p class="text-xs text-base-content/70">
            {{ t('subtitles.options.format.legendLabel') }}
          </p>
          <select
            id="format-select"
            v-model="primaryFormat"
            class="select select-bordered w-full max-w-xs mt-1"
          >
            <option
              v-for="format in subtitleFormatOptions"
              :key="format.value"
              :value="format.value"
            >
              {{ format.label }}
            </option>
          </select>
        </div>
      </div>
    </base-fieldset>

    <div class="divider my-0" />

    <!-- Subtitle Languages -->
    <base-fieldset
      :legend="t('subtitles.options.languages.legend')"
      :label="t('subtitles.options.languages.legendLabel')"
    >
      <div class="flex flex-col gap-4 my-2" :class="{ 'opacity-50 pointer-events-none': !settings.subtitles.enabled }">
        <!-- Quick Preset Actions -->
        <div class="flex flex-wrap items-center gap-2">
          <button
            type="button"
            class="btn btn-xs rounded-lg"
            :class="isPtDefault ? 'btn-primary font-semibold' : 'btn-unselected'"
            @click="setPortugueseDefault"
          >
            {{ t('subtitles.options.languages.suggestedPt') }}
          </button>
          <button
            type="button"
            class="btn btn-xs rounded-lg"
            :class="isPtEn ? 'btn-primary font-semibold' : 'btn-unselected'"
            @click="setPortugueseAndEnglish"
          >
            {{ t('subtitles.options.languages.ptAndEn') }}
          </button>
          <button
            type="button"
            class="btn btn-xs rounded-lg"
            :class="isAllSelected ? 'btn-primary font-semibold' : 'btn-unselected'"
            @click="toggleAllLanguages"
          >
            {{ t('subtitles.options.languages.downloadAll') }}
          </button>
          <button
            type="button"
            class="btn btn-xs btn-ghost text-base-content/60 hover:text-base-content"
            @click="clearLanguages"
          >
            {{ t('subtitles.options.languages.none') }}
          </button>
        </div>

        <!-- Search Input -->
        <div class="w-full flex flex-col md:w-96">
          <label class="label py-1" for="languageSearch">
            <span class="label-text font-semibold text-xs">
              {{ t('subtitles.options.languages.search') }}
            </span>
          </label>
          <input
            id="languageSearch"
            v-model="languageQuery"
            type="search"
            class="input input-sm input-bordered"
            :placeholder="t('subtitles.options.languages.searchPlaceholder')"
          />
        </div>

        <!-- Language Options List -->
        <ul class="max-h-64 overflow-y-auto rounded-lg border border-base-content/10 bg-base-100">
          <li
            v-for="option in filteredLanguageOptions"
            :key="option.code"
            class="border-b border-base-content/5 last:border-b-0 hover:bg-base-200/50 transition-colors"
          >
            <label class="flex cursor-pointer items-center gap-3 px-4 py-2">
              <input
                type="checkbox"
                class="checkbox checkbox-sm checkbox-primary"
                :checked="isLanguageSelected(option.code)"
                :disabled="isAllSelected"
                @change="toggleLanguage(option.code)"
              />
              <span class="flex items-center gap-2">
                <span class="font-medium text-sm">{{ option.englishName }}</span>
                <span
                  v-if="option.nativeName && option.nativeName !== option.englishName"
                  class="text-xs text-base-content/60"
                >
                  {{ `(${option.nativeName})` }}
                </span>
                <span
                  v-if="option.code === 'pt-BR' || option.code === 'pt'"
                  class="badge badge-xs badge-primary font-semibold"
                >
                  {{ t('subtitles.options.languages.defaultBadge') }}
                </span>
              </span>
            </label>
          </li>
          <li v-if="!filteredLanguageOptions.length" class="px-4 py-6 text-center text-sm text-base-content/60">
            {{ t('subtitles.options.languages.noResult', { query: languageQuery }) }}
          </li>
        </ul>

        <!-- Selected Languages Badges -->
        <div class="flex flex-wrap items-center gap-2 text-sm pt-1">
          <span class="font-semibold text-xs">{{ t('subtitles.options.languages.selected') }}</span>
          <template v-if="isAllSelected">
            <span class="badge badge-sm badge-info font-medium">
              {{ t('subtitles.options.languages.allSelected') }}
            </span>
          </template>
          <template v-else>
            <span
              v-if="selectedLanguageBadges.length === 0"
              class="badge badge-sm badge-ghost text-xs"
            >
              {{ t('subtitles.options.languages.none') }}
            </span>
            <span
              v-for="label in selectedLanguageBadges"
              :key="label"
              class="badge badge-sm badge-primary font-medium"
            >
              {{ label }}
            </span>
          </template>
        </div>
      </div>
    </base-fieldset>
  </div>
</template>

<script setup lang="ts">
import { computed, ref } from 'vue';
import { useI18n } from 'vue-i18n';
import BaseFieldset from '../base/BaseFieldset.vue';
import { Settings } from '../../tauri/types/config.ts';
import {
  languageOptions,
  getSubtitleLanguageLabel,
  type SubtitleLanguageOption,
} from '../../helpers/subtitles/languages.ts';
import {
  buildSubtitleFormatOptions,
  getPrimarySubtitleFormat,
} from '../../helpers/subtitles/settings.ts';
import { sanitizeSubtitleFormats, sanitizeSubtitleLanguages } from '../../helpers/subtitles/sanitize.ts';

const settings = defineModel<Settings>({ required: true });
const { t } = useI18n();

const subtitleFormatOptions = buildSubtitleFormatOptions(t);
const languageQuery = ref('');

const languageSelection = computed({
  get: () => settings.value.subtitles.languages,
  set: (value: string[]) => {
    settings.value.subtitles.languages = sanitizeSubtitleLanguages(value);
    if (settings.value.subtitles.languages.length > 0) {
      settings.value.subtitles.enabled = true;
    }
  },
});

const orderedFormats = computed(() =>
  sanitizeSubtitleFormats(settings.value.subtitles.formatPreference),
);

const primaryFormat = computed({
  get: () => orderedFormats.value[0] ?? getPrimarySubtitleFormat(settings.value.subtitles),
  set: (value: string) => {
    settings.value.subtitles.formatPreference = sanitizeSubtitleFormats([value]);
  },
});

const isAllSelected = computed(() => languageSelection.value.includes('all'));

const isPtDefault = computed(() => {
  const langs = languageSelection.value;
  return langs.length === 2 && langs.includes('pt-BR') && langs.includes('pt');
});

const isPtEn = computed(() => {
  const langs = languageSelection.value;
  return langs.length === 3 && langs.includes('pt-BR') && langs.includes('pt') && langs.includes('en');
});

function setPortugueseDefault() {
  settings.value.subtitles.enabled = true;
  languageSelection.value = ['pt-BR', 'pt'];
}

function setPortugueseAndEnglish() {
  settings.value.subtitles.enabled = true;
  languageSelection.value = ['pt-BR', 'pt', 'en'];
}

function clearLanguages() {
  languageSelection.value = [];
}

function toggleAllLanguages() {
  languageSelection.value = isAllSelected.value ? ['pt-BR', 'pt'] : ['all'];
}

function toggleLanguage(code: string) {
  const next = new Set(languageSelection.value);
  if (next.has(code)) {
    next.delete(code);
  } else {
    next.add(code);
  }
  next.delete('all');
  languageSelection.value = Array.from(next);
}

function isLanguageSelected(code: string): boolean {
  return languageSelection.value.includes(code);
}

function matchesQuery(option: SubtitleLanguageOption): boolean {
  const query = languageQuery.value.trim().toLowerCase();
  if (!query) {
    return true;
  }

  return (
    option.englishName.toLowerCase().includes(query)
    || option.nativeName.toLowerCase().includes(query)
    || option.code.toLowerCase().includes(query)
  );
}

const filteredLanguageOptions = computed(() =>
  languageOptions.filter(option => matchesQuery(option) || isLanguageSelected(option.code)),
);

const selectedLanguageBadges = computed(() => {
  if (isAllSelected.value) {
    return [];
  }

  return languageSelection.value
    .map(code => getSubtitleLanguageLabel(code))
    .filter((label, index, array) => array.indexOf(label) === index);
});
</script>
