import { defineStore } from 'pinia';
import { ref } from 'vue';
import { invoke } from '@tauri-apps/api/core';
import { getDefaultLocale, i18n, type Locale } from '../i18n';
import { defaultSettings } from '../tauri/types/config.ts';
import { Settings } from '../tauri/types/config.ts';

type DeepPartial<T> = T extends object ? {
  [P in keyof T]?: DeepPartial<T[P]>;
} : T;

export const useSettingsStore = defineStore('settings', () => {
  const settings = ref<Settings>(defaultSettings);

  async function load(): Promise<Settings> {
    const cfg = await invoke<Settings>('config_get');
    if (cfg.subtitles && Array.isArray(cfg.subtitles.languages)) {
      const langs = cfg.subtitles.languages;
      if ((langs.length === 1 && langs[0] === 'en') || (langs.length === 2 && langs.includes('pt') && langs.includes('pt-BR'))) {
        cfg.subtitles.languages = ['pt-BR'];
        cfg.subtitles.enabled = true;
        cfg.subtitles.includeAutoGenerated = true;
        void patch({ subtitles: cfg.subtitles });
      }
    }
    if (cfg.auth && cfg.auth.cookieBrowser === 'safari') {
      cfg.auth.cookieBrowser = 'none';
      void patch({ auth: cfg.auth });
    }
    applySettings(cfg);
    return cfg;
  }

  async function patch(partial: DeepPartial<Settings>) {
    const newCfg = await invoke<Settings>('config_set', { patch: partial });
    applySettings(newCfg);
  }

  async function reset() {
    const cfg = await invoke<Settings>('config_reset');
    applySettings(cfg);
    return cfg;
  }

  function hasAuthConfigured() {
    return settings.value.auth.cookieFile !== null || settings.value.auth.cookieBrowser !== 'none';
  }

  function applySettings(cfg: Settings) {
    Object.assign(settings.value, cfg);

    if (cfg.appearance.language) {
      const currentLocale: Locale = cfg.appearance.language === 'system'
        ? getDefaultLocale()
        : cfg.appearance.language as Locale;

      i18n.global.locale.value = currentLocale;
      document.documentElement.setAttribute('lang', currentLocale);
    }
  }

  return {
    settings,
    load,
    patch,
    reset,
    hasAuthConfigured,
  };
});
